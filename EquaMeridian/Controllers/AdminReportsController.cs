    [HasPermission("Reports.Export")]
    [HttpGet("active-listings/export/pdf")]
    public async Task<IActionResult> ExportActiveListingsPdf()
    {
        var report = await _repo.GetActiveListingsReportAsync();

        var doc = new PdfReportEngine("Active Listings", "Current live marketplace inventory", GeneratedBy);

        decimal avgRate = report.Listings.Count > 0 ? report.Listings.Average(l => l.DailyRateZAR) : 0;
        var rated = report.Listings.Where(l => l.AverageRating > 0).ToList();
        decimal avgRating = rated.Count > 0 ? rated.Average(l => l.AverageRating) : 0;
        int categoryCount = report.Listings.Select(l => l.CategoryName).Distinct().Count();

        doc.AddKpis(
            new PdfKpi("Active Listings", report.TotalCount.ToString("N0", CultureInfo.InvariantCulture)),
            new PdfKpi("Avg. Daily Rate", Money(avgRate)),
            new PdfKpi("Avg. Rating", rated.Count > 0
                ? avgRating.ToString("N1", CultureInfo.InvariantCulture) + " / 5"
                : "No ratings yet"),
            new PdfKpi("Categories", categoryCount.ToString(CultureInfo.InvariantCulture)));

        // Complexity matrix: simple list reports export tables only (no charts).

        var rows = report.Listings
            .OrderBy(l => l.CategoryName).ThenByDescending(l => l.DailyRateZAR)
            .Select(l => new PdfTableRow(new[]
            {
                l.ListingTitle,
                l.CategoryName,
                l.SupplierName,
                Money(l.DailyRateZAR),
                string.IsNullOrWhiteSpace(l.Location) ? "—" : l.Location!,
                l.AverageRating > 0
                    ? l.AverageRating.ToString("N1", CultureInfo.InvariantCulture)
                    : "—"
            }))
            .ToList();

        doc.AddTable($"All Listings ({report.TotalCount})",
            new[] { "Title", "Category", "Supplier", "Daily Rate", "Location", "Rating" },
            new[] { 130.0, 80.0, 100.0, 75.0, 95.0, 50.0 },
            new[] { false, false, false, true, false, true },
            rows,
            emptyMessage: "No active listings on the marketplace.");

        doc.AddNote("Average rating excludes listings with no reviews. Only listings with status Active are included.");

        var bytes = doc.Build();
        return File(bytes, "application/pdf", $"active-listings-{AppTime.Now:yyyyMMdd-HHmmss}.pdf");
    }

