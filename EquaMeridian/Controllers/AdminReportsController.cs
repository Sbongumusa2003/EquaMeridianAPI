    // ---- Shared PDF formatting helpers ----

    private static string Money(decimal value) => "R" + value.ToString("N2", CultureInfo.InvariantCulture);

    private static string DateRangeSubtitle(DateTime? from, DateTime? to)
    {
        if (from == null && to == null)
            return "Full history \u2014 no date filter applied";
        string f = from?.ToString("d MMM yyyy", CultureInfo.InvariantCulture) ?? "Earliest record";
        string t = to?.ToString("d MMM yyyy", CultureInfo.InvariantCulture) ?? "Latest record";
        return $"Period: {f} \u2013 {t}";
    }

    private static string Pct(decimal part, decimal whole)
    {
        if (whole == 0) return "0%";
        return (part / whole * 100m).ToString("0.0", CultureInfo.InvariantCulture) + "%";
    }

    private static string BuildSupplierPerformanceCsv(SupplierPerformanceReportDto report)
    {
        var sb = new StringBuilder();
        sb.AppendLine("Supplier,Month,Transaction_Count,Subtotal,Platform_Fee,Total_Amount");

        foreach (var supplier in report.Suppliers)
        {
            foreach (var month in supplier.Months)
            {
                sb.AppendLine(string.Join(",",
                    CsvField(supplier.SupplierName),
                    CsvField(month.MonthLabel),
                    month.TransactionCount.ToString(CultureInfo.InvariantCulture),
                    month.Subtotal.ToString(CultureInfo.InvariantCulture),
                    month.PlatformFeeAmount.ToString(CultureInfo.InvariantCulture),
                    month.TotalAmount.ToString(CultureInfo.InvariantCulture)));
            }
            sb.AppendLine(string.Join(",",
                CsvField(supplier.SupplierName), "SUBTOTAL",
                supplier.SupplierTransactionCount.ToString(CultureInfo.InvariantCulture),
                supplier.SupplierSubtotal.ToString(CultureInfo.InvariantCulture),
                supplier.SupplierPlatformFeeAmount.ToString(CultureInfo.InvariantCulture),
                supplier.SupplierTotalAmount.ToString(CultureInfo.InvariantCulture)));
        }

        sb.AppendLine(string.Join(",", "GRAND TOTAL", "",
            report.GrandTransactionCount.ToString(CultureInfo.InvariantCulture),
            report.GrandSubtotal.ToString(CultureInfo.InvariantCulture),
            report.GrandPlatformFeeAmount.ToString(CultureInfo.InvariantCulture),
            report.GrandTotalAmount.ToString(CultureInfo.InvariantCulture)));

        return sb.ToString();
    }

