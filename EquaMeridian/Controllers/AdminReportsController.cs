/// <summary>
/// Reporting & Analytics gaps from the report: a dedicated revenue-summary endpoint (previously
/// only folded into the single dashboard aggregate), a transactional report with control breaks
/// (Category -> Month subtotals, Missing), adjustable criteria (date range + category filter),
/// exportable CSV/PDF, and machinery demand/usage-trend analytics (Missing). Admin-only, same
/// policy the dashboard and audit log already use.
///
/// PDF exports use PdfReportEngine — every PDF gets the EquaMeridian Holdings letterhead (logo +
/// wordmark), a "Generated by / at" stamp, KPI summary cards, real bar/line charts where the data
/// supports one, and a styled, paginated data table (not a plain text dump).
/// </summary>
[ApiController]
[Route("api/admin/reports")]
[Authorize(Policy = "AdminOnly")]
[ResponseCache(NoStore = true, Location = ResponseCacheLocation.None)]
public class AdminReportsController : ControllerBase
{
    private readonly IReportingRepository _repo;
    public AdminReportsController(IReportingRepository repo) => _repo = repo;

    /// <summary>Name of the currently signed-in admin, stamped into every exported report as
    /// "Generated by" — previously every export hardcoded a generic "EquaMeridian Admin Portal"
    /// string regardless of who actually ran it.</summary>
    private string GeneratedBy =>
        User.FindFirstValue(ClaimTypes.Name) ?? User.FindFirstValue(ClaimTypes.Email) ?? "EquaMeridian Admin Portal";

