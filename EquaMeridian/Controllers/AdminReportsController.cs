    [HasPermission("Reports.Export")]
    [HttpGet("monthly-overview/export/pdf")]
    public async Task<IActionResult> ExportMonthlyOverviewPdf([FromQuery] DateTime? from, [FromQuery] DateTime? to)
    {
        var report = await _repo.GetMonthlyOverviewReportAsync(from, to);
        var months = report.Months;
        var effectiveFrom = from ?? (months.Count > 0
            ? new DateTime(months[0].Year, months[0].Month, 1)
            : (DateTime?)null);

        var doc = new PdfReportEngine("Monthly Revenue & Commission Overview",
            DateRangeSubtitle(effectiveFrom, to), GeneratedBy);

        decimal totalRev = months.Sum(m => m.GrossRevenue);
        decimal totalComm = months.Sum(m => m.PlatformCommission);
        int totalBookings = months.Sum(m => m.BookingCount);

        doc.AddKpis(
            new PdfKpi("Total Bookings", totalBookings.ToString("N0", CultureInfo.InvariantCulture)),
            new PdfKpi("Total Revenue", Money(totalRev)),
            new PdfKpi("Total Commission", Money(totalComm)),
            new PdfKpi("Months Shown", months.Count.ToString(CultureInfo.InvariantCulture)));

        if (months.Count >= 1)
        {
            var peak = months.OrderByDescending(m => m.GrossRevenue).First();
            var takeRate = Pct(totalComm, totalRev);
            string insight =
                $"Peak month: {peak.MonthLabel} with {Money(peak.GrossRevenue)} gross " +
                $"({peak.BookingCount} bookings). Platform commission rate across the period: {takeRate}.";
            if (months.Count >= 2)
            {
                var last = months[^1];
                var prev = months[^2];
                if (prev.GrossRevenue > 0)
                {
                    var growth = Math.Round((last.GrossRevenue - prev.GrossRevenue) / prev.GrossRevenue * 100m, 1);
                    insight += $" Latest month vs prior: {(growth >= 0 ? "+" : "")}{growth}% revenue.";
                }
            }
            doc.AddInsight("Performance snapshot", insight);
        }

        if (months.Count > 0)
        {
            doc.AddBarChart("Gross Revenue vs. Platform Commission",
                months.Select(m => ShortMonthLabel(m.MonthLabel)).ToList(),
                new List<PdfChartSeries>
                {
                    new("Gross Revenue", months.Select(m => m.GrossRevenue).ToList(), "D4A017"),
                    new("Platform Commission", months.Select(m => m.PlatformCommission).ToList(), "1A1A1A"),
                });
        }

        var rows = months
            .Select(m => new PdfTableRow(new[]
            {
                m.MonthLabel,
                m.BookingCount.ToString(CultureInfo.InvariantCulture),
                Money(m.GrossRevenue),
                Money(m.PlatformCommission),
                Pct(m.GrossRevenue, totalRev),
                m.BookingCount > 0 ? Money(m.GrossRevenue / m.BookingCount) : "—"
            }))
            .ToList();

        if (months.Count > 0)
        {
            rows.Add(new PdfTableRow(new[]
            {
                "TOTAL",
