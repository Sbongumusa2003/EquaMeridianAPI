    private static string BuildDemandCsv(DemandTrendReportDto report)
    {
        var sb = new StringBuilder();
        sb.AppendLine("Category,Quotation_Requests,Bookings,Conversion_Rate_Percent");
        foreach (var c in report.Categories)
        {
            sb.AppendLine(string.Join(",",
                CsvField(c.CategoryName),
                c.QuotationRequestCount.ToString(CultureInfo.InvariantCulture),
                c.BookingCount.ToString(CultureInfo.InvariantCulture),
                c.ConversionRatePercent.ToString(CultureInfo.InvariantCulture)));
        }
        sb.AppendLine();
        sb.AppendLine("Month,Quotation_Requests,Bookings");
        foreach (var m in report.MonthlyUsage)
        {
            sb.AppendLine(string.Join(",",
                CsvField(m.MonthLabel),
                m.QuotationCount.ToString(CultureInfo.InvariantCulture),
                m.BookingCount.ToString(CultureInfo.InvariantCulture)));
        }
        return sb.ToString();
    }

    private static string CsvField(string? value)
    {
        value ??= string.Empty;
        return value.Contains(',') || value.Contains('"') || value.Contains('\n')
            ? $"\"{value.Replace("\"", "\"\"")}\""
            : value;
    }
