        var report = await _repo.GetActiveListingsReportAsync();
        var sb = new StringBuilder();
        sb.AppendLine("Listing_ID,Title,Category,Supplier,Daily_Rate_ZAR,Location,Avg_Rating,Created_Date");
        foreach (var l in report.Listings)
        {
            sb.AppendLine(string.Join(",",
