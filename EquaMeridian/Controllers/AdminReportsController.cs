    [HasPermission("Reports.Export")]
    [HttpGet("demand-trends/export/pdf")]
    public async Task<IActionResult> ExportDemandTrendsPdf([FromQuery] DateTime? from, [FromQuery] DateTime? to)
    {
        var report = await _repo.GetDemandTrendReportAsync(from, to);

        int totalQuotes = report.Categories.Sum(c => c.QuotationRequestCount);
        int totalBookings = report.Categories.Sum(c => c.BookingCount);
        decimal overallConversion = totalQuotes > 0
            ? Math.Round((decimal)totalBookings / totalQuotes * 100m, 1)
            : 0;

        var doc = new PdfReportEngine("Machinery Demand & Usage Trends", DateRangeSubtitle(report.From, report.To), GeneratedBy);

        doc.AddKpis(
            new PdfKpi("Quotation Requests", totalQuotes.ToString("N0", CultureInfo.InvariantCulture)),
            new PdfKpi("Bookings", totalBookings.ToString("N0", CultureInfo.InvariantCulture)),
            new PdfKpi("Conversion Rate", overallConversion.ToString(CultureInfo.InvariantCulture) + "%"),
            new PdfKpi("Categories Tracked", report.Categories.Count.ToString(CultureInfo.InvariantCulture)));

        if (report.Categories.Count > 0)
        {
            var best = report.Categories.Where(c => c.QuotationRequestCount > 0)
                .OrderByDescending(c => c.ConversionRatePercent).FirstOrDefault();
            var busiest = report.Categories.OrderByDescending(c => c.QuotationRequestCount).First();
            var zeroConv = report.Categories.Count(c => c.QuotationRequestCount > 0 && c.BookingCount == 0);
            string insight =
                $"{busiest.CategoryName} attracted the most demand ({busiest.QuotationRequestCount} quote requests). ";
            if (best != null)
                insight += $"Best conversion: {best.CategoryName} at {best.ConversionRatePercent}%. ";
            if (zeroConv > 0)
                insight += $"{zeroConv} categor{(zeroConv == 1 ? "y has" : "ies have")} quotes with zero bookings — follow up opportunity.";
            doc.AddInsight("Demand snapshot", insight.Trim());
        }

        var topCategories = report.Categories.OrderByDescending(c => c.QuotationRequestCount).Take(10).ToList();
        if (topCategories.Count > 0)
        {
            doc.AddBarChart("Demand by Category",
                topCategories.Select(c => c.CategoryName).ToList(),
                new List<PdfChartSeries>
                {
                    new("Quotation Requests", topCategories.Select(c => (decimal)c.QuotationRequestCount).ToList(), "D4A017"),
                    new("Bookings", topCategories.Select(c => (decimal)c.BookingCount).ToList(), "1A1A1A"),
                },
                valuePrefix: "");
        }

        // Booking share by category — mirrors the on-screen donut chart
        if (topCategories.Count > 0)
        {
            doc.AddDonutChart("Booking share by category", "Where confirmed bookings come from",
                report.Categories.Select(c => c.CategoryName).ToList(),
                report.Categories.Select(c => (decimal)c.BookingCount).ToList(),
                valuePrefix: "");
        }

        if (report.MonthlyUsage.Count > 0)
        {
            doc.AddLineChart("Monthly Usage Trend",
                report.MonthlyUsage.Select(m => ShortMonthLabel(m.MonthLabel)).ToList(),
                new List<PdfChartSeries>
                {
                    new("Quotation Requests", report.MonthlyUsage.Select(m => (decimal)m.QuotationCount).ToList(), "D4A017"),
                    new("Bookings", report.MonthlyUsage.Select(m => (decimal)m.BookingCount).ToList(), "1A1A1A"),
                },
                valuePrefix: "");

            if (report.MonthlyUsage.Count >= 2)
            {
                var last = report.MonthlyUsage[^1];
                var prev = report.MonthlyUsage[^2];
                if (prev.QuotationCount > 0)
                {
                    var qChange = Math.Round((decimal)(last.QuotationCount - prev.QuotationCount) / prev.QuotationCount * 100m, 0);
                    var bChange = prev.BookingCount > 0
                        ? Math.Round((decimal)(last.BookingCount - prev.BookingCount) / prev.BookingCount * 100m, 0)
                        : 0;
                    doc.AddNote(
                        $"Latest month vs prior: quotations {(qChange >= 0 ? "+" : "")}{qChange}%, " +
                        $"bookings {(bChange >= 0 ? "+" : "")}{bChange}%.");
                }
            }
        }

        var rows = report.Categories
            .OrderByDescending(c => c.QuotationRequestCount)
            .Select(c => new PdfTableRow(new[]
            {
                c.CategoryName,
                c.QuotationRequestCount.ToString(CultureInfo.InvariantCulture),
                c.BookingCount.ToString(CultureInfo.InvariantCulture),
                c.ConversionRatePercent + "%",
                totalQuotes > 0 ? Pct(c.QuotationRequestCount, totalQuotes) : "0%"
            }))
            .ToList();

        doc.AddTable("Category Breakdown",
            new[] { "Category", "Quotes", "Bookings", "Conversion", "Demand Share" },
            new[] { 180.0, 70.0, 70.0, 80.0, 90.0 },
            new[] { false, true, true, true, true },
            rows,
            emptyMessage: "No quotation or booking activity in this period.");

        var bytes = doc.Build();
        return File(bytes, "application/pdf", $"demand-trends-{AppTime.Now:yyyyMMdd-HHmmss}.pdf");
    }

