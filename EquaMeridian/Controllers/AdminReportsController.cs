    [HasPermission("Reports.Export")]
    [HttpGet("revenue-summary/export/pdf")]
    public async Task<IActionResult> ExportRevenuePdf(
        [FromQuery] DateTime? from, [FromQuery] DateTime? to, [FromQuery] int? categoryId)
    {
        var report = await _repo.GetRevenueControlBreakReportAsync(from, to, categoryId);

        var doc = new PdfReportEngine("Revenue Summary", DateRangeSubtitle(report.From, report.To), GeneratedBy);

        doc.AddKpis(
            new PdfKpi("Grand Total", Money(report.GrandTotalAmount)),
            new PdfKpi("Transactions", report.GrandTransactionCount.ToString("N0", CultureInfo.InvariantCulture)),
            new PdfKpi("Platform Fees", Money(report.GrandPlatformFeeAmount)),
            new PdfKpi("Categories", report.Categories.Count.ToString(CultureInfo.InvariantCulture)));

        if (report.Categories.Count > 0 && report.GrandTotalAmount > 0)
        {
            var top = report.Categories.OrderByDescending(c => c.CategoryTotalAmount).First();
            var topShare = Pct(top.CategoryTotalAmount, report.GrandTotalAmount);
            var feeRate = Pct(report.GrandPlatformFeeAmount, report.GrandSubtotal);
            doc.AddInsight(
                "Key insight",
                $"{top.CategoryName} is the largest revenue category at {topShare} of platform total " +
                $"({Money(top.CategoryTotalAmount)} across {top.CategoryTransactionCount} transactions). " +
                $"Overall platform take-rate on subtotal is {feeRate}.");
        }

        // Monthly aggregate chart (all categories combined)
        var monthly = report.Categories
            .SelectMany(c => c.Months.Select(m => new { m.MonthLabel, m.Year, m.Month, m.TotalAmount, m.PlatformFeeAmount, m.TransactionCount }))
            .GroupBy(x => new { x.Year, x.Month, x.MonthLabel })
            .OrderBy(g => g.Key.Year).ThenBy(g => g.Key.Month)
            .Select(g => new {
                Label = ShortMonthLabel(g.Key.MonthLabel),
                Revenue = g.Sum(x => x.TotalAmount),
                Fees = g.Sum(x => x.PlatformFeeAmount)
            })
            .ToList();

        if (monthly.Count > 0)
        {
            doc.AddBarChart("Revenue by Month (all categories)",
                monthly.Select(m => m.Label).ToList(),
                new List<PdfChartSeries>
                {
                    new("Revenue (incl. fees)", monthly.Select(m => m.Revenue).ToList(), "D4A017"),
                    new("Platform Fees", monthly.Select(m => m.Fees).ToList(), "1A1A1A"),
                });
        }

        // Category ranking (horizontal) — clearer with long names
        var ranked = report.Categories.OrderByDescending(c => c.CategoryTotalAmount).Take(8).ToList();
        if (ranked.Count > 0)
        {
            doc.AddHorizontalBarChart(
                "Revenue by Category",
                ranked.Select(c => c.CategoryName).ToList(),
                ranked.Select(c => c.CategoryTotalAmount).ToList());
        }

        // Revenue share by category — mirrors the on-screen donut chart
        if (report.Categories.Count > 0)
        {
            doc.AddDonutChart("Revenue share by category", "Proportion of total revenue",
                report.Categories.Select(c => c.CategoryName).ToList(),
                report.Categories.Select(c => c.CategoryTotalAmount).ToList());
        }

        var rows = new List<PdfTableRow>();
        foreach (var category in report.Categories.OrderByDescending(c => c.CategoryTotalAmount))
        {
            rows.Add(new PdfTableRow(new[] { category.CategoryName, "", "", "", "", "" }, PdfRowStyle.GroupHeader));
            foreach (var month in category.Months)
            {
                rows.Add(new PdfTableRow(new[]
                {
                    "  " + month.MonthLabel,
                    month.TransactionCount.ToString(CultureInfo.InvariantCulture),
                    Money(month.Subtotal), Money(month.PlatformFeeAmount), Money(month.TotalAmount),
                    Pct(month.TotalAmount, report.GrandTotalAmount)
                }));
            }
            rows.Add(new PdfTableRow(new[]
            {
                "Category subtotal",
                category.CategoryTransactionCount.ToString(CultureInfo.InvariantCulture),
                Money(category.CategorySubtotal), Money(category.CategoryPlatformFeeAmount),
                Money(category.CategoryTotalAmount),
                Pct(category.CategoryTotalAmount, report.GrandTotalAmount)
            }, PdfRowStyle.Subtotal));
        }
        rows.Add(new PdfTableRow(new[]
        {
            "GRAND TOTAL",
            report.GrandTransactionCount.ToString(CultureInfo.InvariantCulture),
            Money(report.GrandSubtotal), Money(report.GrandPlatformFeeAmount), Money(report.GrandTotalAmount),
            "100%"
        }, PdfRowStyle.GrandTotal));

        doc.AddTable("Category Breakdown",
            new[] { "Category / Month", "Txns", "Subtotal", "Fees", "Total", "Share" },
            new[] { 155.0, 42.0, 90.0, 80.0, 90.0, 55.0 },
            new[] { false, true, true, true, true, true },
            rows,
            emptyMessage: "No invoiced revenue in this period.");

        doc.AddNote("Share is each row's contribution to the grand total. Cancelled invoices are excluded.");

        var bytes = doc.Build();
        return File(bytes, "application/pdf", $"revenue-summary-{AppTime.Now:yyyyMMdd-HHmmss}.pdf");
    }

        [HasPermission("Reports.Export")]
    [HttpGet("revenue-summary/export/xlsx")]
    public async Task<IActionResult> ExportRevenueXlsx(
        [FromQuery] DateTime? from, [FromQuery] DateTime? to, [FromQuery] int? categoryId)
    {
        var report = await _repo.GetRevenueControlBreakReportAsync(from, to, categoryId);
        var headers = new[] { "Category", "Month", "Transaction Count", "Subtotal", "Platform Fee", "Total Amount" };
        var rows = new List<IReadOnlyList<object?>>();

        foreach (var category in report.Categories)
        {
            foreach (var month in category.Months)
            {
                rows.Add(new object?[] { category.CategoryName, month.MonthLabel, month.TransactionCount,
                    month.Subtotal, month.PlatformFeeAmount, month.TotalAmount });
            }
            rows.Add(new object?[] { category.CategoryName, "SUBTOTAL", category.CategoryTransactionCount,
                category.CategorySubtotal, category.CategoryPlatformFeeAmount, category.CategoryTotalAmount });
        }
        rows.Add(new object?[] { "GRAND TOTAL", "", report.GrandTransactionCount,
            report.GrandSubtotal, report.GrandPlatformFeeAmount, report.GrandTotalAmount });

        var bytes = SimpleXlsxWriter.Generate(
            "Revenue Summary", headers, rows,
            reportTitle: "Revenue Summary (by Category, by Month)",
            generatedBy: GeneratedBy);
        return File(bytes, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            $"revenue-summary-{AppTime.Now:yyyyMMdd-HHmmss}.xlsx");
    }

